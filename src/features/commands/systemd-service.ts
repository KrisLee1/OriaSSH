import type { CommandInvocation, CommandRun, PresetAction, RemoteService, ServiceTemplate } from "@/types";
import { literalShellWords, renderInvocation } from "./command-invocation";
import { hasServicePort } from "./command-variable-model";

const systemdStop = /^(systemctl(?: --user)?) stop -- '([A-Za-z0-9][A-Za-z0-9_.@:-]*\.service)'$/;
const backgroundKey = "oria-tunnel.systemd-background.v1";
type BackgroundService = Pick<CommandRun, "serviceId" | "serviceRevision" | "hostId" | "loginId" | "endpoint" | "workflowRuleId">;

export function backgroundServices(): BackgroundService[] {
  try {
    const saved = JSON.parse(localStorage.getItem(backgroundKey) ?? "[]") as BackgroundService[];
    return Array.isArray(saved) ? saved.filter((item) => item?.serviceId && item.hostId) : [];
  } catch {
    return [];
  }
}

export function rememberBackgroundService(run: BackgroundService) {
  const { serviceId, serviceRevision, hostId, loginId, endpoint, workflowRuleId } = run;
  const saved = backgroundServices().filter((item) =>
    item.serviceId !== serviceId || item.hostId !== hostId || item.loginId !== loginId,
  );
  saved.push({ serviceId, serviceRevision, hostId, loginId, endpoint, workflowRuleId });
  try {
    localStorage.setItem(backgroundKey, JSON.stringify(saved));
  } catch {
    // Status can still be refreshed directly from the service menu.
  }
}

export function allowUnloadedSystemdUnit(command: string) {
  return command.replace(
    ' || exit 5\n[ "$load" = loaded ] || exit 5',
    '\nload_result=$?\n[ "$load" != not-found ] || exit 3\n[ "$load_result" -eq 0 ] && [ "$load" = loaded ] || exit 5',
  );
}

// Match the unit-scoped actions generated by the existing systemd templates.
export function systemdService(service?: RemoteService) {
  const probe = service?.control?.statusProbe;
  if (!service || probe?.mode !== "exitCode" ||
      probe.runningCodes.join(",") !== "0" ||
      probe.stoppedCodes.join(",") !== "3" ||
      probe.failedCodes.join(",") !== "4") return undefined;
  const status = service.actions.find((action) => action.id === probe.actionId && action.mode !== "terminal" && !action.confirm);
  if (!status) return undefined;
  for (const stop of service.actions) {
    const match = stop.kind === "stop" && stop.mode !== "terminal" && stop.command.match(systemdStop);
    if (!match) continue;
    const [, tool, unit] = match;
    const statusScript = [
      `load=$(${tool} show --property=LoadState --value -- '${unit}') || exit 5`,
      '[ "$load" = loaded ] || exit 5',
      `state=$(${tool} show --property=ActiveState --value -- '${unit}') || exit 5`,
      'case "$state" in',
      "  active) exit 0 ;;",
      "  inactive) exit 3 ;;",
      "  failed) exit 4 ;;",
      "  *) exit 5 ;;",
      "esac",
    ].join("\n");
    if (status.command === statusScript || status.command === allowUnloadedSystemdUnit(statusScript))
      return { stop, status, unit, startId: service.control?.startActionId };
  }
  return undefined;
}

export function systemdUnit(id: string) {
  return /^[a-z0-9-]{1,64}$/i.test(id) ? `oriassh-${id}` : undefined;
}

// Decode only the old launcher generated by the "Manage with systemd" button.
export function restoreSystemdCommand(service: RemoteService): RemoteService {
  const lifecycle = systemdService(service);
  if (!lifecycle || !/^(?:oriatunnel|oriassh)-[a-z0-9-]{1,64}\.service$/i.test(lifecycle.unit))
    return service;
  const unit = "'" + lifecycle.unit + "'";
  const prefix = [
    'if [ "$(loginctl show-user "$(id -u)" --property=Linger --value 2>/dev/null)" != yes ]; then',
    "  printf '%s\\n' 'systemd user service requires Linger=yes to survive logout.' >&2",
    "  exit 1",
    "fi",
    `if [ "$(systemctl --user show --property=ActiveState --value -- ${unit} 2>/dev/null)" = failed ]; then`,
    `  systemctl --user reset-failed -- ${unit} || exit $?`,
    "fi",
    `systemd-run --user --no-ask-password --service-type=exec --unit=${unit} --setenv=PATH -- /bin/sh -c `,
  ].join("\n");
  return {
    ...service,
    actions: service.actions.map((action) => {
      if (action.id !== lifecycle.startId || action.invocation || action.systemdLaunch ||
          action.kind !== "start" || action.mode === "terminal" || !action.timeoutSecs ||
          !action.command.startsWith(prefix)) return action;
      const body = literalShellWords(action.command.slice(prefix.length));
      if (body?.length !== 1 || !body[0].trim() || body[0].replaceAll("$$", "").includes("$")) return action;
      const command = body[0].replaceAll("$$", "$");
      const invocation = restoreLiteralInvocation(command, !!action.servicePortVariable);
      return { ...action, command, invocation, systemdLaunch: { unit: lifecycle.unit, mode: "persistent" } };
    }),
  };
}

function restoreLiteralInvocation(command: string, variable: boolean): CommandInvocation | undefined {
  if (/[\r\n]/.test(command)) return undefined;
  const words = literalShellWords(command);
  const encoder = new TextEncoder();
  if (!words?.length || !words[0].trim() || words.some((word) => !word || encoder.encode(word).length > 4096) ||
      (variable && hasServicePort(words[0]))) return undefined;
  const [executable, ...values] = words;
  const args: CommandInvocation["arguments"] = [];
  let positionalOnly = false;
  const isOption = (word: string) => word.length <= 128 && /^-[a-z0-9_.-]+$/i.test(word);
  for (let index = 0; index < values.length; index++) {
    const name = values[index];
    if (positionalOnly || !isOption(name)) {
      args.push({ name: "", value: name });
    } else {
      positionalOnly = name === "--";
      const next = values[index + 1];
      const value = !positionalOnly && next !== undefined && !isOption(next) ? values[++index] : null;
      args.push({ name, value });
    }
  }
  const invocation = { executable, arguments: args };
  return args.length <= 128 && renderInvocation(invocation) === command ? invocation : undefined;
}

export function manageServiceWithSystemd(
  draft: RemoteService,
  start: PresetAction,
  template: ServiceTemplate,
  labels: Record<PresetAction["kind"], string>,
): RemoteService {
  const actions = template.actions.filter((action) => action.kind !== "start" && action.kind !== "restart").map((action) => ({
    ...action,
    label: draft.actions.some((saved) => saved.kind === action.kind)
      ? `${labels[action.kind]} · systemd`
      : labels[action.kind],
    command: action.kind === "status" ? allowUnloadedSystemdUnit(action.command) : action.command,
  }));
  const managedStart: PresetAction = {
    ...start,
    mode: "command",
    systemdLaunch: { unit: template.resource, mode: "persistent" },
    timeoutSecs: start.timeoutSecs || 60,
  };
  return {
    ...draft,
    actions: [...draft.actions.map((action) => action.id === start.id ? managedStart : action), ...actions],
    control: {
      ...template.control,
      ...draft.control,
      startActionId: start.id,
      statusProbe: template.control.statusProbe,
      checkAfterActions: true,
    },
  };
}
